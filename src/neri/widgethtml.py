def build() -> str:
    wp = json.loads((ROOT / "reports/widget_percentiles.json").read_text())
    nums = json.loads((ROOT / "reports/numbers.json").read_text())
    N = nums["numbers"]
    v = lambda k: N[k]["value"]
    data = {"files": wp["files"], "top_commands": wp["top_commands"],
            "tips": {"claude_tokens_median": v("claude.overall.a1.always_loaded_tokens.median"), "nested_share": v("claude.overall.a1.on_demand.share_with_nested_files"),
                     "tree_share": v("claude.overall.a8.tree_dump.share_files"), "overview_share": v("claude.overall.a8.overview.share_files"),
                     "bridge_share": v("repo.overall.link.linked_any")},
            "foot": f"neri census of public GitHub · snapshot {config.load()['snapshot']['date']} · generated {wp['generated']} · cells with n < 30 omitted"}
    sc = {}
    for ft in ("claude", "agents"):
        thr = N.get(f"{ft}.overall.sc.threshold_tokens")
        if not thr:
            continue
        sc[ft] = {"threshold": thr["value"]}
        for g in ("established", "long_tail", "stars1k"):
            dist = [N.get(f"{ft}.{g}.sc.dist.{k}", {}).get("value") for k in range(7)]
            if all(x is not None for x in dist):
                sc[ft][g] = {"dist": dist, "n": N[f"{ft}.{g}.sc.dist.0"]["n"]}
    data["sc"] = sc
    out = ROOT / "reports/widget.html"
    out.write_text(PAGE.replace("__DATA__", json.dumps(data, separators=(",", ":"))))
    return f"wrote reports/widget.html ({out.stat().st_size // 1024} KB, self-contained, no network)"
